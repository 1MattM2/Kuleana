INK = (36, 24, 30)          # the hero's outline: the darkest neutral used for characters

def write_js():
    js = "// Generated by tools/palette.py - the master palette. Edit RAMPS there, not here.\n"
    js += "(function () {\n  const R = " + json.dumps({k: [list(c) for c in v] for k, v in RAMPS.items()}) + ";\n"
    js += f"  const INK = {list(INK)};\n"
    js += r'''  const pk = (c) => (255 << 24) | (c[2] << 16) | (c[1] << 8) | c[0];
  const css = (c, a) => (a === undefined ? `rgb(${c[0]},${c[1]},${c[2]})` : `rgba(${c[0]},${c[1]},${c[2]},${a})`);
  const PAL = (window.PAL = { R, INK, pk, css });
  PAL.packed = {}; for (const k in R) PAL.packed[k] = R[k].map(pk);
  // colour at a 0..1 position along a ramp (nearest step, never blended: keeps pixel art clean)
  PAL.at = (name, t) => { const r = R[name]; return r[Math.max(0, Math.min(r.length - 1, Math.round(t * (r.length - 1))))]; };
  PAL.pat = (name, t) => { const r = PAL.packed[name]; return r[Math.max(0, Math.min(r.length - 1, Math.round(t * (r.length - 1))))]; };
  PAL.i = (name, i) => { const r = PAL.packed[name]; return r[Math.max(0, Math.min(r.length - 1, i | 0))]; };
  // 4x4 ordered dither threshold (-0.5..0.5): the only way gradients are made in this game
  const B = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map((v) => v / 16 - 0.5);
  PAL.bayer = (x, y) => B[(x & 3) | ((y & 3) << 2)];
  PAL.dpat = (name, t, x, y, spread) => PAL.pat(name, t + PAL.bayer(x, y) * (spread || 1) / (R[name].length - 1));
})();
'''
    open(os.path.join(ROOT, "js", "palette.js"), "w").write(js)

def swatch():
    rows = list(RAMPS.items()); sw = 26; lab = 96
    w = lab + max(len(v) for _, v in rows) * sw + 10; h = len(rows) * (sw + 6) + 10
    im = Image.new("RGB", (w, h), (24, 20, 28)); d = ImageDraw.Draw(im)
    for i, (k, v) in enumerate(rows):
        y = 6 + i * (sw + 6); d.text((6, y + 8), k, fill=(230, 220, 200))
        for j, c in enumerate(v): d.rectangle([lab + j * sw, y, lab + j * sw + sw - 3, y + sw - 1], fill=c)
    im.save(os.path.join(ROOT, "docs", "palette.png"))

def audit():
    allc = np.array([c for v in RAMPS.values() for c in v], float)
    print(f"{'asset':24s} {'on-palette':>10s}  (pixels within distance 28 of a palette colour)")
    for f in sorted(os.listdir(os.path.join(ROOT, "assets"))):
        if not f.endswith(".png") or " " in f: continue
        a = np.array(Image.open(os.path.join(ROOT, "assets", f)).convert("RGBA")).reshape(-1, 4)
        a = a[a[:, 3] > 0][:, :3].astype(float)
        if len(a) == 0: continue
        if len(a) > 40000: a = a[np.random.RandomState(1).choice(len(a), 40000, replace=False)]
        d = np.sqrt(((a[:, None, :] - allc[None]) ** 2).sum(-1)).min(1)
        print(f"{f:24s} {100 * (d < 28).mean():9.0f}%")

